% Physical parameters
m = 1.4431;          % exact mass from hydrostatics (kg)
C33 = 619.1542;      % heave restoring coefficient (N/m)
rho = 1025;          % kg/m³ (not used here but good to keep)

% Compute RAO (heave motion amplitude per wave amplitude)
RAO = zeros(size(w));
for i = 1:length(w)
    M = m + A33(i);                    % total mass (kg)
    inertia_term = -w(i)^2 * M;
    damping_term = w(i) * B33(i);
    stiffness_term = C33;
    
    denom = sqrt( (inertia_term + stiffness_term)^2 + damping_term^2 );
    RAO(i) = F3_mag(i) / denom;
end

% Plot
figure('Position',[100 100 800 500]);
plot(w, RAO, 'b-', 'LineWidth', 2.5);
grid on;
xlabel('\omega (rad/s)');
ylabel('Heave RAO (m/m)');
title('Heave RAO - Buoy (Capytaine)');
xlim([0 15.5]);
ylim([0 1.05]);

% Optional: add natural frequency estimate
